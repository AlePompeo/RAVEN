"""Generate Pydantic models and TypeScript types from contracts/*.schema.json, plus the RAVEN
parameter registry export (contracts/raven_params.json, frontend/src/contracts/raven_params.ts).

Usage: gen.py [--check]. With --check nothing is written; exit 1 on drift,
exit 2 if generator tooling is missing/failing (run `npm ci` in frontend/).
TS output is formatted by json-schema-to-typescript's bundled prettier (pinned via
the lockfile); no separate prettier pass is applied.
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))  # `backend` importable when run as `python contracts/gen.py`

from backend.domain.raven.export import JSON_PATH, TS_PATH, params_json, params_ts

CONTRACTS = ROOT / "contracts"
PY_OUT = "backend/contracts_models.py"
TS_DIR = "frontend/src/contracts"
JSON2TS = (
    ROOT / "frontend/node_modules/.bin/json2ts"
)  # json-schema-to-typescript, pinned in frontend/package.json
EXIT_TOOLING = 2  # generator tooling missing or failing (distinct from drift = 1)
SPDX = "SPDX-License-Identifier: Apache-2.0"
SCHEMAS = ("telemetry", "state_estimate")


def _title(name: str) -> str:
    return "".join(w.capitalize() for w in name.split("_"))


def _strip_stray_model(py: Path) -> None:
    """Drop the empty root `Model(RootModel[Any])` emitted for the combined wrapper schema."""
    text = py.read_text()
    stray = "class Model(RootModel[Any]):\n    root: Any\n\n\n"
    if stray not in text:
        raise RuntimeError("expected stray Model class not found; update _strip_stray_model")
    text = text.replace(stray, "").replace(
        "from typing import Annotated, Any\n", "from typing import Annotated\n"
    )
    py.write_text(text)


def _run(cmd: list[str]) -> None:
    subprocess.run(cmd, cwd=ROOT, check=True)


def generate(out: Path) -> None:
    """Write all generated files under `out`, mirroring the repo layout."""
    py = out / PY_OUT
    py.parent.mkdir(parents=True, exist_ok=True)
    combined: dict[str, object] = {"$schema": "https://json-schema.org/draft/2020-12/schema"}
    defs: dict[str, object] = {}
    for n in SCHEMAS:
        raw = (CONTRACTS / f"{n}.schema.json").read_text()
        schema = json.loads(raw.replace('"#/$defs/', f'"#/$defs/{_title(n)}/$defs/'))
        schema.pop("$schema", None)
        schema.pop("$id", None)
        defs[_title(n)] = schema
    combined["$defs"] = defs
    tmp_in = out / "combined.schema.json"
    tmp_in.write_text(json.dumps(combined, indent=2, sort_keys=True))
    _run(
        [
            sys.executable, "-m", "datamodel_code_generator",
            "--input", str(tmp_in), "--input-file-type", "jsonschema",
            "--output", str(py), "--output-model-type", "pydantic_v2.BaseModel",
            "--formatters", "ruff-format", "--disable-timestamp", "--use-annotated",
            "--field-constraints", "--use-union-operator",
            "--custom-file-header", f"# {SPDX}",
        ]
    )  # fmt: skip
    tmp_in.unlink()
    _strip_stray_model(py)
    ts = out / TS_DIR
    ts.mkdir(parents=True, exist_ok=True)
    banner = f"/* {SPDX} */\n/* Generated by contracts/gen.py. Do not edit. */"
    for n in SCHEMAS:
        _run(
            [
                str(JSON2TS), str(CONTRACTS / f"{n}.schema.json"),
                "--output", str(ts / f"{n}.ts"), "--cwd", str(CONTRACTS),
                "--bannerComment", banner,
            ]
        )  # fmt: skip
    # parameter registry (backend/domain/raven/params.py): rows for the browser, no schema involved
    (out / JSON_PATH).parent.mkdir(parents=True, exist_ok=True)
    (out / JSON_PATH).write_text(params_json(), encoding="utf-8")
    (out / TS_PATH).write_text(params_ts(), encoding="utf-8")


def _files(base: Path) -> dict[str, bytes]:
    paths = [base / PY_OUT, base / JSON_PATH, *sorted((base / TS_DIR).glob("*.ts"))]
    return {str(p.relative_to(base)): p.read_bytes() for p in paths if p.exists()}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if not JSON2TS.exists():
        print(f"missing {JSON2TS}: run `npm ci` in frontend/", file=sys.stderr)
        return EXIT_TOOLING
    try:
        with tempfile.TemporaryDirectory() as d:
            tmp = Path(d)
            generate(tmp)
            fresh = _files(tmp)
    except (subprocess.CalledProcessError, FileNotFoundError, RuntimeError) as e:
        print(f"contracts generation failed: {e}", file=sys.stderr)
        return EXIT_TOOLING
    if args.check:
        if fresh != _files(ROOT):
            print("contracts drift: run `python contracts/gen.py`", file=sys.stderr)
            return 1
        return 0
    for rel, data in fresh.items():
        dest = ROOT / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)
    return 0


if __name__ == "__main__":
    sys.exit(main())
