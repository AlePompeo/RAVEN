"""RAVEN parameter registry: the single definition of every numeric parameter (migration step M1).

Each parameter has a value, unit, validated bounds, a tag, a source and an owner stage:
`V` = read from a primary source, `D` = derived by a repeatable formula from V values, `I` =
ILLUSTRATIVE (design choice, not verified). Nothing here is a measurement.

M1 moved the values of `backend/domain/lunar/model.py` and `backend/domain/grazing/model.py` here
WITHOUT changing any number (proved by the golden outputs, tests/backend/domain/test_golden.py).
The two legacy models still define different values for similar concepts (for example the carrier
frequency 8.425 GHz vs 8.4 GHz): they stay separate entries, keyed `<scope>.<name>`, until the
intentional unification of docs/domain/raven-model.md (D2, D8, step M8). `DUPLICATED_CONCEPTS`
lists them. The legacy modules read their tables from here (`scope_specs`), so the old names and
responses are unchanged.

The registry imports nothing from the rest of the backend (lowest layer of `backend.domain.raven`).
"""

