class ParamError(ValueError):
    """Invalid parameter. `key` names the parameter; the message never contains the input value."""

    def __init__(self, key: str) -> None:
        super().__init__("invalid parameter")
        self.key = key


@dataclass(frozen=True)
class ParamSpec:
    """One registered parameter. `key` is `<scope>.<name>`; `name` is the legacy key of its scope."""

    scope: str  # lunar | grazing | common
    name: str
    group: str  # legacy table group: link | energy | window | grazing | constants
    stage: str  # owner stage s0..s7
    default: float
    unit: str
    lo: float
    hi: float
    tag: str  # V | D | I
    source: str  # citation, or "illustrative"
    note: str = ""

    @property
    def key(self) -> str:
        return f"{self.scope}.{self.name}"

    def check(self, raw: object) -> float:
        """Validated float within [lo, hi]; raises `ParamError(name)` otherwise (no value in message)."""
        if isinstance(raw, bool) or not isinstance(raw, int | float):
            raise ParamError(self.name)
        v = float(raw)
        if not math.isfinite(v) or v < self.lo or v > self.hi:
            raise ParamError(self.name)
        return v


