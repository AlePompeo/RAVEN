REGISTRY: dict[str, ParamSpec] = {s.key: s for s in (*_LUNAR, *_GRAZING, *_COMMON, *_RF)}
if len(REGISTRY) != len(_LUNAR) + len(_GRAZING) + len(_COMMON) + len(_RF):  # pragma: no cover
    raise RuntimeError("duplicate parameter key in the registry")

# Concepts defined twice with different values in the legacy models; to be unified in step M8.
DUPLICATED_CONCEPTS: dict[str, tuple[str, str]] = {
    n: (f"lunar.{n}", f"grazing.{n}")
    for n in sorted({s.name for s in _LUNAR} & {s.name for s in _GRAZING})
}


def get(key: str) -> ParamSpec:
    """The spec of `<scope>.<name>`; KeyError if unknown."""
    return REGISTRY[key]


def value(key: str) -> float:
    """Default value of `<scope>.<name>`."""
    return REGISTRY[key].default


def scope_specs(scope: str) -> list[ParamSpec]:
    """The specs of one scope in registry order (the order of the legacy tables)."""
    return [s for s in REGISTRY.values() if s.scope == scope]


def resolve(scope: str, overrides: Mapping[str, object] | None = None) -> dict[str, float]:
    """Defaults of `scope` with `overrides` (legacy names) applied and validated.

    Unknown key, non-numeric, non-finite or out-of-range value: `ParamError`, without echoing it.
    """
    specs = {s.name: s for s in scope_specs(scope)}
    over = overrides or {}
    for k in over:
        if k not in specs:
            raise ParamError("unknown")
    return {n: s.check(over.get(n, s.default)) for n, s in specs.items()}


def registry_rows() -> list[dict[str, object]]:
    """Every parameter as a plain row (input of the generated frontend metadata, M2)."""
    return [
        {
            "key": s.key,
            "scope": s.scope,
            "name": s.name,
            "group": s.group,
            "stage": s.stage,
            "default": s.default,
            "unit": s.unit,
            "min": s.lo,
            "max": s.hi,
            "tag": s.tag,
            "source": s.source,
            "note": s.note,
        }
        for s in REGISTRY.values()
    ]
