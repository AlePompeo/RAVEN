"""Deterministic export of the parameter registry for the frontend (RAVEN M2).

`contracts/gen.py` writes the two files below and `--check` fails on drift:

* `contracts/raven_params.json`: the registry rows (key, scope, stage, default, unit, range, tag,
  source), one definition per number;
* `frontend/src/contracts/raven_params.ts`: typed constants for the browser. The TypeScript mirror
  of the link formula (`simula/linkModel.ts`) can import ranges and defaults from here instead of
  keeping hand-copied numbers (not wired yet: the frontend components are unchanged).

Nothing here computes physics. The files carry the registry as it is, tags included.
"""

import json

from backend.domain.raven.params import registry_rows

__all__ = ["JSON_PATH", "TS_PATH", "params_json", "params_ts"]

JSON_PATH = "contracts/raven_params.json"
TS_PATH = "frontend/src/contracts/raven_params.ts"
SPDX = "SPDX-License-Identifier: Apache-2.0"


def params_json() -> str:
    doc = {
        "schema": "raven_params v1: generated from backend/domain/raven/params.py by contracts/gen.py",
        "tags": {
            "V": "read from a primary source",
            "D": "derived by a repeatable formula from V values",
            "I": "illustrative design choice, not verified",
        },
        "parameters": registry_rows(),
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def _ts_string(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def params_ts() -> str:
    from backend.domain.grazing.antenna import STATIONS as stations
    from backend.domain.grazing.bitrate import DEFAULT_RATES_BPS as rates
    from backend.domain.raven.params import value

    rows = registry_rows()
    keys = " | ".join(_ts_string(str(r["key"])) for r in rows)
    out = [
        f"/* {SPDX} */",
        "/* Generated by contracts/gen.py from backend/domain/raven/params.py. Do not edit. */",
        "",
        'export type RavenParamTag = "V" | "D" | "I";',
        'export type RavenStage = "s0" | "s1" | "s2" | "s3" | "s4" | "s5" | "s6" | "s7";',
        f"export type RavenParamKey = {keys};",
        "",
        "export interface RavenParam {",
        "  readonly key: RavenParamKey;",
        "  readonly scope: string;",
        "  readonly name: string;",
        "  readonly group: string;",
        "  readonly stage: RavenStage;",
        "  readonly default: number;",
        "  readonly unit: string;",
        "  readonly min: number;",
        "  readonly max: number;",
        "  readonly tag: RavenParamTag;",
        "  readonly source: string;",
        "  readonly note: string;",
        "}",
        "",
        "export const RAVEN_PARAMS: readonly RavenParam[] = [",
    ]
    for r in rows:
        out.append("  {")
        for k in (
            "key",
            "scope",
            "name",
            "group",
            "stage",
            "default",
            "unit",
            "min",
            "max",
            "tag",
            "source",
            "note",
        ):
            v = r[k]
            out.append(f"    {k}: {_ts_string(v) if isinstance(v, str) else json.dumps(v)},")
        out.append("  },")
    out += [
        "];",
        "",
        "export const RAVEN_PARAM: Readonly<Record<RavenParamKey, RavenParam>> = Object.fromEntries(",
        "  RAVEN_PARAMS.map((p) => [p.key, p]),",
        ") as Record<RavenParamKey, RavenParam>;",
        "",
        "/** Bit rates of the link tables (grazing.bitrate.DEFAULT_RATES_BPS), the same set as /api/raven/parameters. */",
        f"export const RAVEN_RATES_BPS: readonly number[] = {json.dumps([float(r) for r in rates])};",
        "/** Station gains: the 34 m value is rf.station_gain_dbi (D); the 18 m value is the legacy station table (I). */",
        "export const RAVEN_STATION_GAIN_DBI = {",
        f"  dsn34: {json.dumps(value('rf.station_gain_dbi'))},",
        f"  dsn18: {json.dumps(float(stations['dsn18'].gain_dbi))},",
        "} as const;",
        "",
    ]
    return "\n".join(out)
