"""Rounded-ridge compensation table R(nu, radius): bilinear interpolation of a versioned file.

The table (`data/compensation_table.json`, generated by `scripts/gen_compensation_table.py`, extra
`[ml]` only needed there) holds R = L_splitstep - J_exact [dB] on nu in [-1.5, 3.0] x radius
{0 ... 400} m. At run time only numpy is used: bilinear interpolation in (nu, log10(radius + 1)).

Reported per query: the correction (smooth trend; the GP below nu = -0.78 interpolates the Fresnel
oscillations, so there the moving-average trend is used), an UNCERTAINTY (the oscillation envelope
around the correction: never applied as correction), the > 4 MAD anomaly flag of the surrounding
cells, and `clamped` when (nu, radius) lies outside the grid (saturated, uncertainty = |correction|).

ROUNDED-RIDGE POLICY (docs/domain/validation.md, "Validazione radio", 2026-11-04):
 * default correction = T(m, n) of ITU-R P.526-9 sec. 4.2 eq. (28)-(32), checked on the text
   (`ridge_correction`); it uses the actual d1, d2 and wavelength;
 * this split-step table (plane wave, absorbing ridge, d1 = 2000 m) is kept as a COMPARISON: its
   difference from T is reported as uncertainty. A convergence study showed the stored table is not
   converged in the march step (dx = 2 m: up to about 0.5 dB low at radius 400 m) and that the refined
   simulation stays about 15-45 % below T for 0 <= nu <= 3 (radius 20-400 m);
 * JPL226 eq. (35)-(38) (L_A -> 0 for d2 >> d1) is not used: its parameter m = f^(1/3) psi has no
   radius in it, so it cannot describe the radius dependence (see the doc).
`consistency_diagnostic` computes the three numbers; the analysis returns them as a declared limit.
"""

