Arr = NDArray[np.float64]
TABLE_PATH = Path(__file__).with_name("data") / "compensation_table.json"
OSC_NU = -0.78
EARTH_FAR_M = 1.0e12  # d2 for "Earth at infinity" (T changes by < 1e-6 dB from 3.8e8 m)
INCONSISTENCY_TEXT = (
    "Tre fonti non concordano: ITU-R P.526-9 eq. (30)-(32) da' fino a 4.2 dB a raggio 400 m "
    "(d1 = 2000 m, nu = 3); lo split-step della tabella 2.4 dB (non convergente nel passo: "
    "raffinato circa 2.9 dB); JPL 42-226 eq. (35)-(38) dicono che la correzione svanisce per Terra "
    "lontana, ma il loro parametro non contiene il raggio. Nessuna e' una misura."
)
POLICY_TEXT = (
    "Correzione predefinita: T(m, n) di ITU-R P.526-9 par. 4.2 (testo verificato), troncata a >= 0. "
    "La tabella split-step resta come confronto: |ITU - split-step| e' riportata come incertezza."
)


@dataclass(frozen=True)
class CompensationTable:
    nu: Arr
    radius_m: Arr
    correction_db: Arr  # [radius, nu]
    envelope_db: Arr
    anomaly: NDArray[np.bool_]
    simulated_db: Arr
    provenance: dict[str, Any]
    validation: dict[str, Any]
    version: str
    file_sha256: str

    @property
    def log_radius(self) -> Arr:
        return np.asarray(np.log10(self.radius_m + 1.0), dtype=np.float64)

    def info(self) -> dict[str, Any]:
        return {
            "version": self.version,
            "file_sha256": self.file_sha256,
            "nu_range": [float(self.nu[0]), float(self.nu[-1])],
            "radius_range_m": [float(self.radius_m[0]), float(self.radius_m[-1])],
            "provenance": self.provenance,
            "validation": self.validation,
            "status": "simulata, non validata",
        }


@lru_cache(maxsize=2)
def _load(path: str) -> CompensationTable:
    raw_bytes = Path(path).read_bytes()
    raw = json.loads(raw_bytes)
    nu = np.asarray(raw["nu"], dtype=np.float64)
    rad = np.asarray(raw["radius_m"], dtype=np.float64)
    corr = np.asarray(raw["correction_db"], dtype=np.float64)
    env = np.asarray(raw["oscillation_envelope_db"], dtype=np.float64)
    an = np.asarray(raw["anomaly"], dtype=bool)
    sim = np.asarray(raw["simulated_db"], dtype=np.float64)
    shape = (rad.size, nu.size)
    if not (corr.shape == env.shape == an.shape == sim.shape == shape):
        raise ValueError("compensation table: inconsistent shapes")
    if not (np.all(np.isfinite(corr)) and np.all(np.isfinite(env)) and np.all(np.diff(nu) > 0)):
        raise ValueError("compensation table: invalid values")
    return CompensationTable(
        nu,
        rad,
        corr,
        env,
        an,
        sim,
        raw["provenance"],
        raw["validation"],
        str(raw["version"]),
        hashlib.sha256(raw_bytes).hexdigest(),
    )


def load_table(path: Path | None = None) -> CompensationTable:
    return _load(str(path if path is not None else TABLE_PATH))


def _locate(grid: Arr, x: Arr) -> tuple[NDArray[np.intp], Arr]:
    i = np.clip(np.searchsorted(grid, x, side="right") - 1, 0, grid.size - 2)
    t = (x - grid[i]) / (grid[i + 1] - grid[i])
    return i, np.asarray(t, dtype=np.float64)


def _bilinear(tab: Arr, i: Any, j: Any, ti: Any, tj: Any) -> Arr:
    """tab[radius, nu] at radius cell i (+ti) and nu cell j (+tj)."""
    a = tab[i, j] * (1 - tj) + tab[i, j + 1] * tj
    b = tab[i + 1, j] * (1 - tj) + tab[i + 1, j + 1] * tj
    return np.asarray(a * (1 - ti) + b * ti, dtype=np.float64)


def table_correction(
    nu: ArrayLike, radius_m: ArrayLike, table: CompensationTable | None = None
) -> tuple[Arr, Arr, NDArray[np.bool_], NDArray[np.bool_]]:
    """Vectorised (correction_db, uncertainty_db, anomaly, clamped) at (nu, radius). NaN -> ValueError."""
    tb = table if table is not None else load_table()
    v = np.asarray(nu, dtype=np.float64)
    r = np.asarray(radius_m, dtype=np.float64)
    v, r = np.broadcast_arrays(v, r)
    if not (np.all(np.isfinite(v)) and np.all(np.isfinite(r)) and np.all(r >= 0)):
        raise ValueError("invalid nu or radius")
    y = np.log10(r + 1.0)
    clamped = (v < tb.nu[0]) | (v > tb.nu[-1]) | (y > tb.log_radius[-1])
    vc = np.clip(v, tb.nu[0], tb.nu[-1])
    yc = np.clip(y, tb.log_radius[0], tb.log_radius[-1])
    j, tj = _locate(tb.nu, vc)
    i, ti = _locate(tb.log_radius, yc)
    corr = _bilinear(tb.correction_db, i, j, ti, tj)
    env = _bilinear(tb.envelope_db, i, j, ti, tj)
    anom = tb.anomaly[i, j] | tb.anomaly[i, j + 1] | tb.anomaly[i + 1, j] | tb.anomaly[i + 1, j + 1]
    unc = np.where(clamped, np.maximum(env, np.abs(corr)), env)
    return corr, np.asarray(unc, dtype=np.float64), np.asarray(anom), np.asarray(clamped)


class TableCorrection:
    """`RoundedRidgeCorrection` backed by the versioned table (no scikit-learn at run time)."""

    def __init__(self, table: CompensationTable | None = None) -> None:
        self.table = table if table is not None else load_table()

    def correction_db(self, nu: float, radius_m: float) -> CorrectionResult:
        if not (math.isfinite(nu) and math.isfinite(radius_m) and radius_m >= 0):
            raise ValueError("invalid nu or radius")
        c, u, a, k = table_correction(nu, radius_m, self.table)
        return CorrectionResult(float(c), "table", float(u), bool(a), bool(k))


def default_correction() -> RoundedRidgeCorrection:
    """The table-backed implementation of the `RoundedRidgeCorrection` protocol."""
    return TableCorrection()


def p526_rounded_term_db(
    nu: ArrayLike, radius_m: ArrayLike, d1_m: ArrayLike, d2_m: ArrayLike, wavelength_m: float
) -> Arr:
    """T(m, n) of ITU-R P.526-9 sec. 4.2 p. 17, eq. (30a)-(32) (text read 2026-11-04). Broadcasts.

    m = R (d1+d2)/(d1 d2) / (pi R / lambda)^(1/3)   (31);  n = h (pi R / lambda)^(2/3) / R   (32),
    with h from nu by eq. (22).
    T = 7.2 m^1/2 - (2 - 12.5 n) m + 3.6 m^3/2 - 0.8 m^2                       m n <= 4   (30a)
    T = -6 - 20 log10(m n) + 7.2 m^1/2 - (2 - 17 n) m + 3.6 m^3/2 - 0.8 m^2     m n > 4    (30b)
    R = 0 gives 0 ("as R tends to zero, T(m,n) also tend to zero", sec. 4.2). The source measures h, d1
    and d2 to the projected-ray vertex, not to the physical tip (about 0.007 dB in the model-doc case).
    """
    v, r, d1, d2 = np.broadcast_arrays(
        *(np.asarray(a, dtype=np.float64) for a in (nu, radius_m, d1_m, d2_m))
    )
    if wavelength_m <= 0 or np.any(r < 0) or np.any(d1 <= 0) or np.any(d2 <= 0):
        raise ValueError("invalid geometry")
    h = v / np.sqrt(2.0 * (d1 + d2) / (wavelength_m * d1 * d2))
    rs = np.where(r > 0, r, 1.0)
    k = np.pi * rs / wavelength_m
    m = rs * (d1 + d2) / (d1 * d2) / np.cbrt(k)
    n = h * k ** (2.0 / 3.0) / rs
    mn = m * n
    sq = np.sqrt(m)
    tail = 3.6 * m * sq - 0.8 * m * m
    small = 7.2 * sq - (2.0 - 12.5 * n) * m + tail
    big = -6.0 - 20.0 * np.log10(np.maximum(mn, 1e-300)) + 7.2 * sq - (2.0 - 17.0 * n) * m + tail
    t = np.where(mn <= 4.0, small, big)
    return np.asarray(np.where(r > 0, t, 0.0), dtype=np.float64)


def ridge_correction(
    nu: ArrayLike,
    radius_m: ArrayLike,
    d1_m: ArrayLike,
    wavelength_m: float,
    d2_m: ArrayLike = EARTH_FAR_M,
    table: CompensationTable | None = None,
) -> tuple[Arr, Arr, NDArray[np.bool_], NDArray[np.bool_], Arr]:
    """Rounded-ridge correction by the policy of docs/domain/validation.md ("Validazione radio").

    Returns (correction_db, uncertainty_db, anomaly, clamped, splitstep_db):
     * correction = max(T(m, n), 0): ITU-R P.526-9 eq. (28)-(32) at the actual d1, d2 and wavelength.
       Negative T (only for nu < 0, outside the obstruction case the clause describes) is clamped to 0;
     * splitstep_db = the simulated table (d1 = 2000 m, lambda = 0.0357 m), kept as comparison;
     * uncertainty = max(table uncertainty, |correction - splitstep|): the model disagreement is an
       error bar, never added to the correction. `anomaly`/`clamped` refer to the comparison table.
    """
    t = np.maximum(p526_rounded_term_db(nu, radius_m, d1_m, d2_m, wavelength_m), 0.0)
    s, u, a, k = table_correction(nu, radius_m, table)
    unc = np.maximum(u, np.abs(t - s))
    return np.asarray(t, dtype=np.float64), np.asarray(unc, dtype=np.float64), a, k, s


def consistency_diagnostic(
    table: CompensationTable | None = None,
    d1_m: float = 2000.0,
    wavelength_m: float = 0.0357,
    radii_m: tuple[float, ...] = (50.0, 100.0, 200.0, 400.0),
    nus: tuple[float, ...] = (0.0, 1.0, 2.0, 3.0),
) -> dict[str, Any]:
    """Split-step table vs ITU-R P.526-9 T(m, n) vs the JPL226 statement (0 dB), Earth at infinity.

    Same geometry as the table (d2 = 1e12 m). Returns the per-cell values, the table/T ratios and the
    policy in force (ITU default, split-step as uncertainty band).
    """
    tb = table if table is not None else load_table()
    cells: list[dict[str, Any]] = []
    ratios: list[float] = []
    t_max = 0.0
    for r in radii_m:
        for v in nus:
            c, _u, _a, _k = table_correction(v, r, tb)
            t = float(p526_rounded_term_db(v, r, d1_m, EARTH_FAR_M, wavelength_m))
            t_max = max(t_max, t)
            ratio = round(float(c) / t, 3) if t > 1e-9 else None
            if ratio is not None:
                ratios.append(ratio)
            cells.append(
                {
                    "radius_m": r,
                    "nu": v,
                    "table_db": round(float(c), 3),
                    "p526_db": round(t, 3),
                    "ratio_table_over_p526": ratio,
                }
            )
    return {
        "text": INCONSISTENCY_TEXT,
        "reference_d1_m": d1_m,
        "table_max_db": round(float(np.max(tb.correction_db)), 3),
        "p526_max_db": round(t_max, 3),
        "jpl226_claim_db": 0.0,
        "ratio_table_over_p526_min": round(min(ratios), 3) if ratios else None,
        "ratio_table_over_p526_max": round(max(ratios), 3) if ratios else None,
        "splitstep_converged": False,
        "cells": cells,
        "policy": POLICY_TEXT,
        "status": "politica: ITU-R P.526-9 predefinita, split-step come banda; nessuna validazione sperimentale",
    }
